class VariaveisSemInicializacao_01 {
    public static void main(String[] args) {
        int x;
        double y;
        boolean flag;
        String texto;

        x = 42;
        y = 3.5;
        flag = true;
        texto = "ok";

        if (flag) {
            System.out.println(x);
            System.out.println(y);
            System.out.println(texto);
        }
    }
}