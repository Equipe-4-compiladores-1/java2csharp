class MenosUnario_01 {
    public static void main(String[] args) {
        int positivo = 12;
        int negativo = -12;
        int invertido = -positivo;
        int precedencia = -2 * 3;
        int agrupado = -(positivo + 3);
        double fracao = -2.5;
        System.out.println(negativo);
        System.out.println(invertido);
        System.out.println(precedencia);
        System.out.println(agrupado);
        System.out.println(fracao);
    }
}
