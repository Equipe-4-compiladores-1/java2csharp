class TiposByteShort {
    public static void main(String[] args) {
    }

    byte identidadeByte(byte valor) {
        byte copia = valor;
        return copia;
    }

    short identidadeShort(short valor) {
        short copia = valor;
        return copia;
    }

    short ampliarByte(byte valor) {
        return valor;
    }

    int ampliarShort(short valor) {
        return valor;
    }

    int somar(byte a, short b) {
        return a + b;
    }
}
